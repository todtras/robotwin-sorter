def _self_check() -> None:
    """import 시점에 설정값 정합성을 확인합니다.

    사람이 숫자를 잘못 고쳤을 때 실행 도중이 아니라 시작하자마자
    알려주는 것이 목적입니다.
    """
    assert WORKSPACE_X[0] < WORKSPACE_X[1], "WORKSPACE_X는 (최소, 최대) 순서"
    assert WORKSPACE_Y[0] < WORKSPACE_Y[1], "WORKSPACE_Y는 (최소, 최대) 순서"
    assert len(CALIB_IMAGE_POINTS) == 4, "캘리브레이션 대응점은 정확히 4개"
    assert len(CALIB_IMAGE_POINTS) == len(CALIB_WORLD_POINTS), \
        "이미지 점과 월드 점의 개수가 다릅니다"
    assert set(BIN_POSITIONS) == set(BIN_COLORS), \
        "BIN_POSITIONS와 BIN_COLORS의 키가 다릅니다"
    assert 0.0 <= CONF_THRESHOLD <= 1.0, "CONF_THRESHOLD는 0~1"

    for name, (x, y, _z) in BIN_POSITIONS.items():
        reach = (x ** 2 + y ** 2) ** 0.5
        if reach > 0.8:
            raise ValueError(
                f"{name}이 베이스에서 {reach:.2f}m 떨어져 있어 "
                f"KUKA iiwa 도달거리(약 0.8m)를 넘습니다."
            )


_self_check()
